/** Always-present tokens supplied by the producer for every IA event. */
export const IA_BASE_TOKENS = ['subjectName', 'reference'] as const;

const BY_CODE = new Map<string, IaCommunicationEntry>(
  INTERNAL_AUDIT_COMMUNICATION_CATALOGUE.map((entry) => [entry.eventCode, entry]),
);

export function internalAuditEntry(eventCode: string): IaCommunicationEntry | null {
  return BY_CODE.get(String(eventCode ?? '').trim().toUpperCase()) ?? null;
}

/** Full token vocabulary (base tokens + business facts) for an event. */
export function internalAuditTokens(entry: IaCommunicationEntry): string[] {
  return [...IA_BASE_TOKENS, ...entry.facts];
}

/** Template family code (<= 60 chars) for an event. */
export function internalAuditFamilyCode(entry: IaCommunicationEntry): string {
  return `ia_${entry.eventCode.toLowerCase().replace(/\./g, '_')}`.slice(0, 60);
}

export const INTERNAL_AUDIT_EVENT_CODES = INTERNAL_AUDIT_COMMUNICATION_CATALOGUE.map(
  (entry) => entry.eventCode,
);
