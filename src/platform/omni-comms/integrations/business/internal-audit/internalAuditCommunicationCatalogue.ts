/**
 * INTERNAL AUDIT → OMNI-COMMS canonical communication catalogue (Wave 4).
 *
 * Single source of truth for every Internal Audit business moment that owes a
 * communication, the semantic recipient role that receives it, the channels the
 * Hub may use, and the token vocabulary the published contract enforces.
 *
 * This module is PURE DATA + PURE FUNCTIONS. It imports no Supabase client, no
 * React and no provider SDK. Internal Audit business code never chooses a
 * template, a channel, a sender or a provider — it only publishes facts.
 *
 * Canonical naming: INTERNAL_AUDIT.<ENTITY>.<ACTION> (three uppercase segments,
 * enforced by `omni_comms_event_definition_code_format_chk`).
 */

export const INTERNAL_AUDIT_MODULE_CODE = 'INTERNAL_AUDIT';

/** Semantic recipient roles. Never a persistence type, never a channel choice. */
export const IA_RECIPIENT_ROLES = [
  'lead_auditor',
  'head_of_audit',
  'qa_reviewer',
  'audit_committee',
  'action_owner',
  'auditee_contact',
  'department_head',
] as const;
export type IaRecipientRole = (typeof IA_RECIPIENT_ROLES)[number];

export type IaCommunicationClass =
  | 'transactional'
  | 'service'
  | 'operational'
  | 'legal_mandatory';

export type IaPriority = 'low' | 'normal' | 'high' | 'urgent';

export type IaChannel = 'email' | 'in_app';

export interface IaCommunicationEntry {
  /** Registered three-segment Omni-Comms event code. */
  eventCode: string;
  /** Durable business entity type (lowercase table-ish name). */
  entityType: string;
  /** Business lifecycle domain, used for grouping and reporting only. */
  domain:
    | 'PLAN'
    | 'ENGAGEMENT'
    | 'REQUEST'
    | 'FINDING'
    | 'REPORT'
    | 'ACTION'
    | 'FOLLOWUP';
  name: string;
  description: string;
  communicationClass: IaCommunicationClass;
  priority: IaPriority;
  /** Primary semantic recipient role for the obligation. */
  recipientRole: IaRecipientRole;
  /** Channels the Hub may consider. The Hub still decides what is sent. */
  channels: IaChannel[];
  /** Short human headline used as the email subject / in-app title stem. */
  headline: string;
  /** One-sentence body lead. */
  lead: string;
  /**
   * Business facts (beyond the always-present `subjectName` and `reference`)
   * the published contract requires.
   */
  facts: string[];
  /** Whether this event can legitimately recur for the same entity. */
  repeatable: boolean;
  /** In-app deep link pattern; `:id` is replaced with the entity id. */
  deepLink: string;
}

